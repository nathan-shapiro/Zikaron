@dataclass(frozen=True, slots=True)
class Query:
    family: str
    text: str
    truth: frozenset[int]
    #: Chunks removed from the ranking before scoring: the one holding a heading line, and any
    #: chunk heading an identically-titled section elsewhere in the corpus. Both contain the query
    #: verbatim and neither is truth, so leaving them in measures the distractor rather than the
    #: retrieval. Empty for the span families, which have no such construction.
    excluded: frozenset[int] = frozenset()
    #: Body chunks of other identically-titled sections. Not used by the shipped oracle; the
    #: sensitivity analysis either counts them as truth or excludes them from the ranking.
    same_title_bodies: frozenset[int] = frozenset()
    #: How many sections in the corpus share this query's title, this one included.
    title_multiplicity: int = 1


@dataclass(slots=True)
class Fetched:
    query: Query
    dense: tuple[arms.ArmRow, ...]
    lexical: tuple[arms.ArmRow, ...]
    lexical_failed: bool = False


@dataclass(slots=True)
class Chunk:
    chunk_id: int
    path: str
    start_line: int
    end_line: int
    text: str


@dataclass(slots=True)
class Instrument:
    """What the query set is, measured rather than asserted."""

    headings_seen: int = 0
    headings_in_fence: int = 0
    headings_generic: int = 0
    duplicate_titles: int = 0
    excluded_total: int = 0
    #: How many sampled queries share their title with N sections, keyed by N.
    multiplicity: Counter[int] = field(default_factory=Counter)
    notes: dict[str, object] = field(default_factory=dict)


def _tokens(text: str) -> list[str]:
    return [m.group(0).lower() for m in _WORD.finditer(text)]


def _document_frequency(chunks: Sequence[Chunk]) -> Counter[str]:
    df: Counter[str] = Counter()
    for chunk in chunks:
        df.update(set(_tokens(chunk.text)))
    return df


def _span_of(chunk: Chunk, rng: random.Random) -> str | None:
    """A contiguous run of `SPAN_WORDS` ordinary words from a chunk, or None if it has too few."""
    words = _tokens(chunk.text)
    if len(words) < SPAN_WORDS * 2:
        return None
    start = rng.randrange(0, len(words) - SPAN_WORDS)
    return " ".join(words[start : start + SPAN_WORDS])


def _masked(span: str, df: Counter[str], *, fraction: float) -> str:
    """`span` with its most distinctive terms removed.

    **This does not starve the lexical arm**, which the preregistration claimed and this run
    measured false: every surviving term is still an exact match in the target, so BM25 keeps a
    shorter but perfect hit. Kept because the family is a valid measurement of *exact-phrase
    lookup* even though it is an invalid instrument for arm balance.
    """
    words = span.split()
    if not words:
        return span
    ranked = sorted(set(words), key=lambda w: (df.get(w, 0), w))
    median = len(ranked) // 2
    candidates = ranked[:median] or ranked[:1]
    drop = set(candidates[: max(1, round(len(candidates) * fraction))])
    return " ".join(w for w in words if w not in drop)


def _file_lines(group: Sequence[Chunk]) -> list[tuple[int, str]]:
    """A file's lines as `(line number, text)`, reconstructed from its chunks.

    Invariant 16 makes chunks whole-line and a partition of the file, so concatenating them in
    `start_line` order recovers the file exactly. Reconstructing rather than re-reading from disk
    keeps the instrument measuring **what was indexed**, which is the only thing retrieval can see.

    **Split on `\\n` and nothing else, which is the product's own rule and matters here for the
    product's own reason.** `chunking.py` records M22's decision that a line ends at `\\n` alone
    because `str.splitlines()` also breaks on nine further characters — a form feed, a lone `\\r`,
    `\\x1c` to `\\x1e`, `\\x85`, U+2028, U+2029 — so on a file containing any of them `splitlines`
    numbers every subsequent line differently from git, an editor, and the chunker that produced
    `start_line`. An earlier revision of this harness used `splitlines`, which would have shifted
    heading line numbers silently on exactly the files where it mattered.

    The reliance on invariant 16 is asserted rather than trusted: a chunk must yield exactly the
    lines its own range claims.
    """
    lines: list[tuple[int, str]] = []
    for chunk in group:
        text = chunk.text.removesuffix("\n")
        chunk_lines = text.split("\n")
        expected = chunk.end_line - chunk.start_line + 1
        if len(chunk_lines) != expected:
            raise AssertionError(
                f"chunk {chunk.chunk_id} in {chunk.path} spans lines "
                f"{chunk.start_line}-{chunk.end_line} ({expected}) but holds {len(chunk_lines)}"
            )
        for offset, line in enumerate(chunk_lines):
            lines.append((chunk.start_line + offset, line))
    return lines


def _headings_of(group: Sequence[Chunk], instrument: Instrument) -> list[tuple[int, str]]:
    """Structural headings in one file: `(line number, title)`, fenced text excluded.

    A `## ` line inside a fenced block is a shell comment or a YAML key, not a section, and would
    become a query against a "section" that does not exist. **Measured on this corpus, that never
    happens: 0 of 2,586 headings fell inside a fence** — so the guard is correct and, here,
    unexercised. An earlier revision of this docstring asserted RFCs "are full of them", which was
    written from expectation and refuted by the harness's own counter in the same run.
    Mirrors `tests/design_tables.py`'s parser, with
    an unterminated fence treated as closing at end of file rather than refused: this is somebody
    else's corpus and a malformed document is data, not an error.
    """
    found: list[tuple[int, str]] = []
    in_fence = False
    for line_no, line in _file_lines(group):
        if line.lstrip().startswith(_FENCE):
            in_fence = not in_fence
            continue
        match = _HEADING.match(line)
        if not match:
            continue
        instrument.headings_seen += 1
        if in_fence:
            instrument.headings_in_fence += 1
            continue
        if match.group(2).strip().lower() in _GENERIC:
            instrument.headings_generic += 1
            continue
        found.append((line_no, match.group(2).strip()))
    return found


def _heading_queries(
    chunks: Sequence[Chunk], rng: random.Random, wanted: int, instrument: Instrument
) -> list[Query]:
    """Section headings, with truth the section's chunks and the exact-match chunks excluded.

    "Section" means up to the next heading of **any** level 2 to 4, not the subtree.
    """
    by_path: dict[str, list[Chunk]] = {}
    for chunk in chunks:
        by_path.setdefault(chunk.path, []).append(chunk)
    for group in by_path.values():
        group.sort(key=lambda c: c.start_line)

    per_file = {path: _headings_of(group, instrument) for path, group in by_path.items()}

    # Every section in the corpus, resolved once: its heading-holding chunks and its body chunks.
    # Both are needed per *title* rather than per occurrence, because a title repeated across RFCs
    # is a guaranteed exact-match distractor. Measured over the sampled queries: 14 of 150 carry a
    # repeat at all, 136 are unique. An earlier revision reported 146 by counting over every
    # section in the corpus under a field named for the sampled set, which sent a review round
    # chasing a distortion that is not there.
    sections: list[tuple[str, str, set[int], set[int]]] = []
    for path, group in by_path.items():
        headings = per_file[path]
        last_line = group[-1].end_line
        for index, (line_no, title) in enumerate(headings):
            section_end = headings[index + 1][0] - 1 if index + 1 < len(headings) else last_line
            holding = {c.chunk_id for c in group if c.start_line <= line_no <= c.end_line}
            body = {
                c.chunk_id
                for c in group
                if c.chunk_id not in holding
                and c.start_line <= section_end
                and c.end_line > line_no
            }
            sections.append((title, title.lower(), holding, body))

    titled_holders: dict[str, set[int]] = {}
    titled_bodies: dict[str, set[int]] = {}
    titled_count: Counter[str] = Counter()
    for _, key, holding, body in sections:
        titled_holders.setdefault(key, set()).update(holding)
        titled_bodies.setdefault(key, set()).update(body)
        titled_count[key] += 1

    found: list[Query] = []
    for title, key, holding, body in sections:
        if not body:
            continue
        excluded = (holding | titled_holders[key]) - body
        found.append(
            Query(
                family="heading",
                text=title,
                truth=frozenset(body),
                excluded=frozenset(excluded),
                # The bodies of *other* identically-titled sections. Under the shipped oracle these
                # score as wrong answers, which review round 2 identified as filtered ranking only
                # half-applied: their heading chunks are removed and their bodies are not, so for a
                # title appearing in ten RFCs, nine sections on the same subject are negatives.
                # Carried so the sensitivity analysis can treat them as truth or exclude them.
                same_title_bodies=frozenset(titled_bodies[key] - body),
                title_multiplicity=titled_count[key],
            )
        )
    rng.shuffle(found)
    sampled = found[:wanted]
    # Counted over the **sampled** queries, not over every section in the corpus: the question is
    # what the family this conclusion rests on actually contains. Note the sampling is over
    # heading *occurrences*, so a title appearing k times is k times as likely to be drawn — the
    # sample is size-biased toward ambiguous titles, which is why the distribution is reported
    # rather than a mean.
    for query in sampled:
        instrument.multiplicity[query.title_multiplicity] += 1
        instrument.excluded_total += len(query.excluded)
        if query.title_multiplicity > 1:
            instrument.duplicate_titles += 1
    return sampled


def build_queries(
    chunks: Sequence[Chunk], per_family: int, instrument: Instrument | None = None
) -> list[Query]:
    instrument = instrument if instrument is not None else Instrument()
    # A fixed seed is the point: the query set must be reproducible across runs of the grid, so
    # that two cells are compared on identical queries rather than on two samples.
    rng = random.Random(SEED)  # noqa: S311 — sampling a query set, not generating a secret
    df = _document_frequency(chunks)
    queries: list[Query] = []

    usable = [c for c in chunks if len(_tokens(c.text)) >= SPAN_WORDS * 2]
    rng.shuffle(usable)
    for chunk in usable[:per_family]:
        span = _span_of(chunk, rng)
        if span is None:
            continue
        truth = frozenset({chunk.chunk_id})
        queries.append(Query(family="verbatim", text=span, truth=truth))
        queries.append(Query(family="masked-50", text=_masked(span, df, fraction=0.5), truth=truth))
        queries.append(
            Query(family="masked-100", text=_masked(span, df, fraction=1.0), truth=truth)
        )

    queries.extend(_heading_queries(chunks, rng, per_family, instrument))
    return queries


def fuse(fetched: Fetched, *, rrf_k: int, depth: int, weight: float) -> list[int]:
    """One fused ranking, best first, with the query's excluded distractors removed.

    `weight` is the dense arm's share.

    **The total order is the product's, not a convenient one.** `search.py::_fuse` orders by fused
    score, then the **best rank any arm gave the chunk**, then the chunk id; an earlier revision of
    this harness used score-then-id, dropping the middle key. Ties are common at `w = 0` and `w = 1`
    where every score is `1/(k + rank)` over one arm, so the missing key was not decorative — and a
    harness that ranks differently from the product cannot report "the shipped cell". Round 1 of
    review asked for an assertion that the two agree; matching the product outright is the stronger
    answer, since an assertion only fails after the divergence has already been measured.
    """
    scores: dict[int, float] = {}
    best_rank: dict[int, int] = {}
    # **A zero-weight arm contributes nothing, and must not be entered at all.** An earlier
    # revision added its rows with score 0.0, so whenever the surviving arm returned fewer than ten
    # chunks the zero-scored rows filled the tail of the top ten — ordered by the *silenced* arm's
    # rank. Review round 2 caught it from the JSON: `(10, 10, 0.0)` scored 0.2515 on `heading`
    # against `(60, 50, 0.0)`'s 0.2475, when both notes and the preregistration assert single-arm
    # cells are invariant to `rrf_k` and depth. The leak flattered the lexical-only arm, so every
    # contrast against it was conservative — but the invariance claim was false as written, and a
    # cell that is supposed to *be* one arm must be exactly that.
    if weight > 0.0:
        for row in fetched.dense[:depth]:
            scores[row.chunk_id] = scores.get(row.chunk_id, 0.0) + weight / (rrf_k + row.rank)
            best_rank[row.chunk_id] = min(best_rank.get(row.chunk_id, row.rank), row.rank)
    if weight < 1.0:
        for row in fetched.lexical[:depth]:
            scores[row.chunk_id] = scores.get(row.chunk_id, 0.0) + (1.0 - weight) / (
                rrf_k + row.rank
            )
            best_rank[row.chunk_id] = min(best_rank.get(row.chunk_id, row.rank), row.rank)
    for chunk_id in fetched.query.excluded:
        scores.pop(chunk_id, None)
    return sorted(scores, key=lambda cid: (-scores[cid], best_rank[cid], cid))


def capped(ranking: Sequence[int], paths: dict[int, str], *, limit: int) -> list[int]:
    """`ranking` under the shipped per-file cap — what a caller actually receives.

    Mirrors `zikaron/core/knowledge/search.py::_capped`: walk the fused order, admit a chunk while
    its file has fewer than `MAX_CHUNKS_PER_FILE` admitted, stop at `limit`.
    """
    kept: list[int] = []
    per_file: Counter[str] = Counter()
    for chunk_id in ranking:
        path = paths.get(chunk_id, "")
        if per_file[path] >= MAX_CHUNKS_PER_FILE:
            continue
        kept.append(chunk_id)
        per_file[path] += 1
        if len(kept) >= limit:
            break
    return kept


def reciprocal_rank(ranking: Sequence[int], truth: frozenset[int], *, at: int = 10) -> float:
    for position, chunk_id in enumerate(ranking[:at], start=1):
        if chunk_id in truth:
            return 1.0 / position
    return 0.0


def hit_at(ranking: Sequence[int], truth: frozenset[int], *, at: int = 5) -> int:
    return int(any(cid in truth for cid in ranking[:at]))


def bootstrap(diffs: Sequence[float], *, seed: int = SEED) -> tuple[float, float, float]:
    """Observed paired mean difference and its 95% percentile bootstrap interval."""
    rng = random.Random(seed)  # noqa: S311 — resampling, not generating a secret
    observed = statistics.fmean(diffs)
    means = sorted(
        statistics.fmean(rng.choices(diffs, k=len(diffs))) for _ in range(BOOTSTRAP_RESAMPLES)
    )
    lower = means[int(0.025 * BOOTSTRAP_RESAMPLES)]
    upper = means[int(0.975 * BOOTSTRAP_RESAMPLES)]
    return observed, lower, upper


def _arm_tokens(text: str) -> set[str]:
    """Tokens as the **lexical arm** sees them, which is not how `_tokens` sees them.

    `chunks_fts` tokenizes with `unicode61` (`ddl.py`) and the query side builds terms from
    `str.isalnum()` runs (`retrieval/query.py`): both split on `_` and admit digit-led and
    two-character tokens. `_WORD` keeps `_` inside a token and demands a leading letter and three
    characters, so it reads `20160210_range_leases` as one token where the arm reads `20160210`,
    `range`, `leases`.

    **That difference made the `text + path` overlap column a no-op**: it reported values identical
    to the text-only column to four decimals across all 150 queries, which is what review round 2
    noticed. An instrument that cannot see the match it is measuring reports that there is none.
    """
    out: set[str] = set()
    current: list[str] = []
    for character in text:
        if character.isalnum():
            current.append(character.lower())
        elif current:
            out.add("".join(current))
            current = []
    if current:
        out.add("".join(current))
    return out


def overlap_report(queries: Sequence[Query], byid: dict[int, Chunk]) -> dict[str, object]:
    """How much of each query appears verbatim in its own answer — the validity measurement.

    Measured two ways, because the lexical arm indexes `text` **and** `path` (`ddl.py`'s
    `chunks_fts`): against chunk text alone, and against text plus the path's own tokens. For
    multi-chunk truth the statistic is the **maximum over truth chunks**, which is the generous
    reading — it asks whether *any* true chunk contains the query.
    """
    out: dict[str, object] = {}
    for family in sorted({q.family for q in queries}):
        text_only: list[float] = []
        with_path: list[float] = []
        for query in (q for q in queries if q.family == family):
            terms = _arm_tokens(query.text)
            if not terms:
                continue
            text_only.append(
                max(len(terms & _arm_tokens(byid[t].text)) / len(terms) for t in query.truth)
            )
            with_path.append(
                max(
                    len(terms & _arm_tokens(byid[t].text + " " + byid[t].path)) / len(terms)
                    for t in query.truth
                )
            )
        out[family] = {
            "n": len(text_only),
            "text_mean": round(statistics.fmean(text_only), 4),
            "text_min": round(min(text_only), 4),
            "text_plus_path_mean": round(statistics.fmean(with_path), 4),
            "at_zero_overlap": sum(1 for v in text_only if v == 0.0),
            "at_zero_overlap_with_path": sum(1 for v in with_path if v == 0.0),
        }
    return out


async def load_chunks(db: aiosqlite.Connection) -> list[Chunk]:
    rows = await db.execute_fetchall(
        "SELECT id, path, start_line, end_line, text FROM chunks ORDER BY id"
    )
    return [Chunk(int(a), str(b), int(c), int(d), str(e)) for a, b, c, d, e in rows]


async def fetch_all(
    db: aiosqlite.Connection, queries: Sequence[Query], encoder: object, config: object
) -> list[Fetched]:
    fetched: list[Fetched] = []
    for query in queries:
        if not query.text.strip():
            continue
        built = await asyncio.to_thread(
            arms.unit_query,
            query.text,
            encoder=encoder,
            prefix=config.get_str("embed_prefix_query"),  # type: ignore[attr-defined]
            max_terms=config.get_int("fts_query_max_terms"),  # type: ignore[attr-defined]
        )
        dense = await arms.dense(db, vector=built.prepared.vector, fusion_depth=MAX_DEPTH)
        expression = built.prepared.lexical.expression if built.prepared.lexical else None
        lexical: tuple[arms.ArmRow, ...] = ()
        failed = False
        if expression:
            try:
                lexical = await arms.lexical(db, expression=expression, fusion_depth=MAX_DEPTH)
            except aiosqlite.Error:
                failed = True
        else:
            failed = True
        fetched.append(Fetched(query=query, dense=dense, lexical=lexical, lexical_failed=failed))
    return fetched


def score_grid(
    fetched: Sequence[Fetched], paths: dict[int, str]
) -> tuple[list[dict[str, object]], dict[tuple[int, int, float], dict[str, list[float]]]]:
    """Every cell's per-family means, and the per-query reciprocal ranks behind them."""
    families = sorted({f.query.family for f in fetched})
    per_cell: dict[tuple[int, int, float], dict[str, list[float]]] = {}
    cells: list[dict[str, object]] = []
    for rrf_k in RRF_K_GRID:
        for depth in DEPTH_GRID:
            for weight in WEIGHT_GRID:
                key = (rrf_k, depth, weight)
                rrs: dict[str, list[float]] = {f: [] for f in families}
                hits: dict[str, list[int]] = {f: [] for f in families}
                capped_rrs: dict[str, list[float]] = {f: [] for f in families}
                capped_hits: dict[str, list[int]] = {f: [] for f in families}
                for item in fetched:
                    ranking = fuse(item, rrf_k=rrf_k, depth=depth, weight=weight)
                    family = item.query.family
                    rrs[family].append(reciprocal_rank(ranking, item.query.truth))
                    hits[family].append(hit_at(ranking, item.query.truth))
                    shown = capped(ranking, paths, limit=10)
                    capped_rrs[family].append(reciprocal_rank(shown, item.query.truth))
                    capped_hits[family].append(
                        hit_at(capped(ranking, paths, limit=LIMIT_PER_KB), item.query.truth)
                    )
                per_cell[key] = rrs
                cell: dict[str, object] = {
                    "rrf_k": rrf_k,
                    "fusion_depth": depth,
                    "dense_weight": weight,
                    "shipped": key == SHIPPED,
                }
                everything: list[float] = []
                for family in families:
                    everything.extend(rrs[family])
                    cell[f"mrr10_{family}"] = round(statistics.fmean(rrs[family]), 4)
                    cell[f"hit5_{family}"] = round(statistics.fmean(hits[family]), 4)
                    cell[f"mrr10_capped_{family}"] = round(statistics.fmean(capped_rrs[family]), 4)
                    cell[f"hit5_capped_{family}"] = round(statistics.fmean(capped_hits[family]), 4)
                cell["mrr10_pooled"] = round(statistics.fmean(everything), 4)
                cells.append(cell)
    return cells, per_cell


def sensitivity(fetched: Sequence[Fetched]) -> dict[str, object]:
    """`heading` under three oracles, to test whether same-titled sections decide the conclusion.

    Review round 2's third blocker: the shipped oracle removes other identically-titled sections'
    **heading** chunks from the ranking but leaves their **bodies** in, where they score as wrong
    answers — so for a title appearing in ten RFCs, nine sections on the same subject are
    negatives. Filtered ranking only half-applied. The two defensible completions bracket it:

    - `widened` — those bodies **count as truth**, on the reading that a section titled the same
      thing in another RFC is a legitimate answer to the title as a query.
    - `strict` — those bodies are **excluded from the ranking**, the full filtered-ranking
      analogue, so the query is scored only against its own section and unrelated text.

    If the three agree on sign and on clearing the bar, the ambiguity does not decide anything and
    the closure stands; if they disagree, the closure needs the qualifier.
    """
    variants: dict[str, object] = {}
    for label in ("shipped_oracle", "widened", "strict"):
        cells: dict[str, list[float]] = {}
        for name, key in (
            ("shipped", (SHIPPED[0], SHIPPED[1], SHIPPED[2])),
            ("lexical_only", (SHIPPED[0], SHIPPED[1], 0.0)),
            ("dense_only", (SHIPPED[0], SHIPPED[1], 1.0)),
        ):
            scores: list[float] = []
            for item in fetched:
                if item.query.family != "heading":
                    continue
                query = item.query
                if label == "widened":
                    query = replace(query, truth=query.truth | query.same_title_bodies)
                elif label == "strict":
                    query = replace(query, excluded=query.excluded | query.same_title_bodies)
                probe = Fetched(query=query, dense=item.dense, lexical=item.lexical)
                ranking = fuse(probe, rrf_k=key[0], depth=key[1], weight=key[2])
                scores.append(reciprocal_rank(ranking, query.truth))
            cells[name] = scores
        entry: dict[str, object] = {
            name: round(statistics.fmean(values), 4) for name, values in cells.items()
        }
        for arm in ("lexical_only", "dense_only"):
            observed, lower, upper = bootstrap(
                [s - a for s, a in zip(cells["shipped"], cells[arm], strict=True)]
            )
            entry[f"shipped_minus_{arm}"] = {
                "delta": round(observed, 4),
                "ci": [round(lower, 4), round(upper, 4)],
                "ci_excludes_zero": not (lower <= 0 <= upper),
            }
        variants[label] = entry
    return variants


def by_arm(
    per_cell: dict[tuple[int, int, float], dict[str, list[float]]], families: Sequence[str]
) -> dict[str, object]:
    """Each family at the shipped cell and at each single-arm extreme — fixed cells, not maxima.

    Review round 1's finding 6: calling the span families' result "entirely artefactual" discards a
    real measurement about a real query class. They are an invalid instrument for arm *balance* and
    a valid measurement of *exact-phrase lookup*, and the two read off the same table — which only
    works if the table compares like with like, so every column here is one cell.
    """
    out: dict[str, object] = {}
    for family in families:
        out[family] = {
            label: round(statistics.fmean(per_cell[key][family]), 4)
            for label, key in (
                ("shipped", (SHIPPED[0], SHIPPED[1], SHIPPED[2])),
                ("lexical_only", (SHIPPED[0], SHIPPED[1], 0.0)),
                ("dense_only", (SHIPPED[0], SHIPPED[1], 1.0)),
            )
        }
    return out


def as_written_bar(
    cells: Sequence[dict[str, object]],
    per_cell: dict[tuple[int, int, float], dict[str, list[float]]],
    families: Sequence[str],
) -> list[dict[str, object]]:
    """Every cell passing the preregistered thresholds **as written** — pooled, not `heading`.

    Review round 1's first blocker: the note applied thresholds 1, 2 and 4 to `heading` after the
    data was seen, while the preregistration defined them on the pooled quantity. Evaluating the
    bar as written is the only way to say whether "no cell clears it" is true of the bar that was
    actually fixed in advance, so it is computed here rather than argued about.
    """
    shipped = next(c for c in cells if c["shipped"])
    shipped_key = (SHIPPED[0], SHIPPED[1], SHIPPED[2])
    shipped_pooled = [v for f in families for v in per_cell[shipped_key][f]]
    passing: list[dict[str, object]] = []
    for cell in cells:
        if cell["shipped"]:
            continue
        gain = float(cell["mrr10_pooled"]) - float(shipped["mrr10_pooled"])
        if gain < EFFECT_BAR:
            continue
        regressions = {
            f: float(cell[f"mrr10_{f}"]) - float(shipped[f"mrr10_{f}"]) for f in families
        }
        if min(regressions.values()) < -REGRESSION_BAR:
            continue
        # **Threshold 4 has two readings and the preregistration fixed neither.** "The gain is not
        # confined to `verbatim`" can mean *some other family also gains* (literal, applied here)
        # or *the >= 0.02 survives with `verbatim` dropped* (strict). Review round 2 asked which;
        # rather than choose, both are reported, so the ambiguity is closed by measurement.
        elsewhere = [v for f, v in regressions.items() if f != "verbatim" and v > 0]
        if not elsewhere:
            continue
        key = (int(cell["rrf_k"]), int(cell["fusion_depth"]), float(cell["dense_weight"]))
        cell_pooled = [v for f in families for v in per_cell[key][f]]
        non_verbatim = [f for f in families if f != "verbatim"]
        strict_gain = statistics.fmean(
            [v for f in non_verbatim for v in per_cell[key][f]]
        ) - statistics.fmean([v for f in non_verbatim for v in per_cell[shipped_key][f]])
        observed, lower, upper = bootstrap(
            [c - s for c, s in zip(cell_pooled, shipped_pooled, strict=True)]
        )
        # Threshold 2, actually applied rather than merely reported. Every cell reaching here
        # happens to pass it, but a function whose docstring says "passing all four" must filter
        # on all four — otherwise the day one does not pass is the day the count is wrong.
        if lower <= 0 <= upper:
            continue
        passing.append(
            {
                "rrf_k": cell["rrf_k"],
                "fusion_depth": cell["fusion_depth"],
                "dense_weight": cell["dense_weight"],
                "pooled_gain": round(gain, 4),
                "worst_family_delta": round(min(regressions.values()), 4),
                #: Threshold 1's gain recomputed with `verbatim` dropped — threshold 4's strict
                #: reading. A cell clears the bar under that reading only if this is >= EFFECT_BAR.
                "non_verbatim_pooled_gain": round(strict_gain, 4),
                "clears_strict_threshold_4": strict_gain >= EFFECT_BAR,
                "bootstrap": [round(observed, 4), round(lower, 4), round(upper, 4)],
                "ci_excludes_zero": not (lower <= 0 <= upper),
            }
        )
    return passing


async def main() -> int:
    if len(sys.argv) < _REQUIRED_ARGS:
        print(__doc__)
        return 2
    workspace = Path(sys.argv[1]).resolve()
    store_dir = workspace / ".zikaron"
    kb_name = sys.argv[2].lower()
    per_family = int(sys.argv[3]) if len(sys.argv) > _REQUIRED_ARGS else DEFAULT_PER_FAMILY

    config = resolve(workspace / "system.toml", workspace / "project.toml")
    async with aiosqlite.connect(store_dir / "memory.db") as memory:
        found = await memory.execute_fetchall(
            "SELECT id FROM knowledge_bases WHERE name = ?", (kb_name,)
        )
    if not found:
        print(f"no knowledge base named {kb_name!r} in {store_dir}")
        return 2
    kb_id = UUID(str(found[0][0]))

    encoder = await asyncio.to_thread(FastEmbedEncoder.load, config.get_str("embed_model"))
    knowledge = await KnowledgeDatabase.open(store_dir, kb_id)
    try:
        db = knowledge.connection
        chunks = await load_chunks(db)
        byid = {c.chunk_id: c for c in chunks}
        paths = {c.chunk_id: c.path for c in chunks}
        instrument = Instrument()
        queries = build_queries(chunks, per_family, instrument)
        fetched = await fetch_all(db, queries, encoder, config)
    finally:
        await knowledge.close()

    families = sorted({f.query.family for f in fetched})
    cells, per_cell = score_grid(fetched, paths)
    shipped_key = (SHIPPED[0], SHIPPED[1], SHIPPED[2])

    # The three comparisons the conclusion rests on, every one a *fixed* cell rather than a grid
    # maximum: the shipped configuration against each single-arm extreme, on `heading`.
    contrasts: dict[str, object] = {}
    for label, key in (
        ("lexical_only", (SHIPPED[0], SHIPPED[1], 0.0)),
        ("dense_only", (SHIPPED[0], SHIPPED[1], 1.0)),
    ):
        diffs = [
            s - a
            for s, a in zip(per_cell[shipped_key]["heading"], per_cell[key]["heading"], strict=True)
        ]
        observed, lower, upper = bootstrap(diffs)
        contrasts[label] = {
            "shipped_minus_arm": round(observed, 4),
            "ci": [round(lower, 4), round(upper, 4)],
            "ci_excludes_zero": not (lower <= 0 <= upper),
        }

    best_heading = max(cells, key=lambda c: c["mrr10_heading"])
    best_key = (
        int(best_heading["rrf_k"]),
        int(best_heading["fusion_depth"]),
        float(best_heading["dense_weight"]),
    )
    diffs = [
        b - s
        for b, s in zip(
            per_cell[best_key]["heading"], per_cell[shipped_key]["heading"], strict=True
        )
    ]
    observed, lower, upper = bootstrap(diffs)
    contrasts["best_heading_vs_shipped"] = {
        "cell": {k: best_heading[k] for k in ("rrf_k", "fusion_depth", "dense_weight")},
        "gain": round(observed, 4),
        "ci": [round(lower, 4), round(upper, 4)],
        "ci_excludes_zero": not (lower <= 0 <= upper),
        "note": "post-selection: this is the grid maximum, so the interval is a winner's-curse "
        "interval — conservative for retaining a null, not an estimate of this cell's true effect",
    }

    print(
        json.dumps(
            {
                "load_average_1m": round(os.getloadavg()[0], 2),
                "cpu_count": os.cpu_count(),
                "store_dir": str(store_dir),
                "knowledge_base": kb_name,
                "chunks": len(chunks),
                "files": len({c.path for c in chunks}),
                "non_markdown_chunks": sum(1 for c in chunks if not c.path.endswith(".md")),
                # **A sample fact, not a construction fact, so it is measured rather than
                # asserted.** The build admitted 9 PlantUML files and an SVG, whose XML tokenizes
                # to plenty of admissible words — so a span family *could* draw a query from one,
                # and ~20 of ~2,500 usable chunks against 150 draws makes "none" nowhere near
                # certain a priori. The note says zero; this is where that zero comes from.
                # (`heading` is zero by construction: those files carry no `## ` lines.)
                "queries_with_truth_in_non_markdown": {
                    family: sum(
                        1
                        for item in fetched
                        if item.query.family == family
                        and any(not paths[t].endswith(".md") for t in item.query.truth)
                    )
                    for family in families
                },
                "queries": len(fetched),
                "queries_by_family": {
                    f: sum(1 for i in fetched if i.query.family == f) for f in families
                },
                "lexical_failures": sum(1 for f in fetched if f.lexical_failed),
                "seed": SEED,
                "max_depth": MAX_DEPTH,
                "bootstrap_resamples": BOOTSTRAP_RESAMPLES,
                "shipped_cell": {
                    "rrf_k": SHIPPED[0],
                    "fusion_depth": SHIPPED[1],
                    "dense_weight": SHIPPED[2],
                },
                "instrument": {
                    "headings_seen": instrument.headings_seen,
                    "headings_dropped_in_fence": instrument.headings_in_fence,
                    "headings_dropped_generic": instrument.headings_generic,
                    "heading_queries_with_duplicate_title": instrument.duplicate_titles,
                    "chunks_excluded_from_ranking": instrument.excluded_total,
                    "overlap": overlap_report([f.query for f in fetched], byid),
                },
                "contrasts": contrasts,
                "by_arm": by_arm(per_cell, families),
                "heading_oracle_sensitivity": sensitivity(fetched),
                "heading_title_multiplicity": dict(sorted(instrument.multiplicity.items())),
                "cells_passing_preregistered_bar_as_written": as_written_bar(
                    cells, per_cell, families
                ),
                "cells": cells,
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
