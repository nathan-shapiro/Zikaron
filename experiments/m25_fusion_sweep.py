#!/usr/bin/env python
"""Sweep `rrf_k`, `fusion_depth` and an arm weight against a real knowledge base.

**Preregistered**: `research/m25-fusion-sweep-preregistration.md` fixes the metric, the query
families, the grid and the decision thresholds, and was written before this ran. Read it before
reading any number this prints; two of its claims are withdrawn in place there.

**This harness produces every number in `research/m25-fusion-sweep.md`.** An earlier revision did
not — the bootstrap and the instrument-overlap table were computed in throwaway scripts, so the
note's two load-bearing figures could not be regenerated by anyone, including their author. Review
round 1 found that, and everything those scripts did is now here.

**Why the grid is cheap.** Both arms are fetched once per query at `MAX_DEPTH` and truncated for
every smaller `fusion_depth`. That is exact rather than an approximation: the dense arm is `vec0`,
which brute-forces, so its top-`MAX_DEPTH` prefix *is* its top-`d` for every `d <= MAX_DEPTH`; the
lexical arm is `ORDER BY bm25(...) LIMIT`, whose prefix property is the same. If either ever stopped
being exhaustive this equivalence would break with no symptom, which is why it is written down here
rather than assumed.

**The arm weight is implemented here and nowhere else.** `ranking.rrf_score` is unweighted and is
shared with the memory store; this harness re-implements fusion locally so that measuring a weight
costs no product change. Landing one is a decision for after there is a number.

**Seven instrument corrections, all from review rounds 1 and 2, each recorded at its own site**
(round 3 found stale figures and framing, and changed no instrument): fenced
headings are not structure; the chunk holding a heading line is removed from the ranking rather than
only from truth; the fused order matches the product's; a zero-weight arm no longer enters the pool;
overlap is tokenized as the lexical arm tokenizes; lines split on `\\n` alone; and the multiplicity
counters count the sampled queries rather than every section in the corpus. Four of the seven
changed a published figure, and the last one changed a review round's conclusion.
**The pattern across all of them is one thing**: each had a symptom visible in this harness's own
output — a column identical to its neighbour, two cells that should have matched and did not, a
counter named for one population and computed over another — and none was noticed by reading
conclusions rather than the instrument.

Run, exactly as reported:
    .venv/bin/python experiments/m25_fusion_sweep.py <store-dir> <kb-name> 150
"""

